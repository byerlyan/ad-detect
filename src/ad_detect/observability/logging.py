"""Structured-enough local logging with defensive secret redaction."""

from __future__ import annotations

import logging
from collections.abc import Mapping
from typing import Any

SENSITIVE_KEYS = frozenset({"credential", "credentials", "password", "pin", "secret", "token"})


def redact(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {
            str(key): "[REDACTED]" if str(key).lower() in SENSITIVE_KEYS else redact(item)
            for key, item in value.items()
        }
    if isinstance(value, (list, tuple)):
        return [redact(item) for item in value]
    return value


def configure_logging(level: int = logging.INFO) -> None:
    logging.basicConfig(
        level=level,
        format="%(asctime)s %(levelname)s %(name)s %(message)s",
    )
